"""
Pydantic v2 schemas for Phase 6: Grounded AI Investigation & Reconciliation Explanations.
"""

import uuid
from decimal import Decimal
from typing import Any

from pydantic import BaseModel, Field

from app.schemas.common import ProcureMindBaseSchema


class MonetaryAmount(ProcureMindBaseSchema):
    """Pairs every monetary value with its ISO-4217 currency code."""

    amount: Decimal = Field(..., description="Monetary quantity with exact Decimal precision")
    currency: str = Field(..., min_length=3, max_length=3, description="ISO-4217 currency code")


class AuthoritativeFinancialFacts(ProcureMindBaseSchema):
    """
    Authoritative reconciliation calculations extracted directly from persisted PostgreSQL records.
    Every financial value is paired with its currency code; cross-currency arithmetic is forbidden.
    """

    invoice_total: MonetaryAmount | None = Field(
        default=None, description="Persisted commercial invoice total"
    )
    payment_gross: MonetaryAmount | None = Field(
        default=None, description="Persisted gross payment proceeds"
    )
    fee_amount: MonetaryAmount | None = Field(
        default=None, description="Persisted provider fee deductions"
    )
    net_amount: MonetaryAmount | None = Field(
        default=None, description="Persisted net proceeds post-deduction"
    )
    unexplained_difference: MonetaryAmount | None = Field(
        default=None, description="Unexplained remainder from active discrepancy calculation"
    )
    currencies_match: bool = Field(
        default=True,
        description="Indicates whether all financial components share the same currency",
    )
    currency_mismatch_warning: str | None = Field(
        default=None,
        description="Warning notice if transaction mixes currencies, forbidding silent subtraction",
    )
    calculation_breakdown: dict[str, Any] | None = Field(
        default=None, description="Snapshot calculation dictionary from Phase 4 engine"
    )
    is_reconciled: bool = Field(
        default=False, description="Whether transaction has approved allocations covering invoice"
    )
    open_discrepancy_count: int = Field(
        default=0, description="Count of active open or acknowledged discrepancies"
    )


class InvestigationRequest(ProcureMindBaseSchema):
    """Client request for transaction investigation."""

    question: str = Field(
        ...,
        min_length=3,
        max_length=1000,
        description="Inquiry regarding transaction status, fee breakdown, or discrepancies",
    )
    discrepancy_id: uuid.UUID | None = Field(
        default=None,
        description="Optional discrepancy UUID to focus investigation upon",
    )


class LLMInvestigationOutput(BaseModel):
    """Schema for validating structured output generated by the LLM provider."""

    explanation: str = Field(
        ..., description="Grounded natural language narrative explaining the trade records"
    )
    cited_record_ids: list[str] = Field(
        default_factory=list,
        description="List of record UUID strings cited from the supplied context",
    )
    missing_information: list[str] = Field(
        default_factory=list,
        description="List of missing documents, evidence, or records needed for reconciliation",
    )
    suggested_next_action: str | None = Field(
        default=None,
        description="Recommended operational step for human auditor (no autonomous execution)",
    )
    draft_clarification_message: str | None = Field(
        default=None,
        description="Drafted message for counterparty, buyer, or exporter requesting clarification",
    )
    requires_human_review: bool = Field(
        default=True,
        description="Explicit flag indicating human oversight is required",
    )
    policy_refusal: bool = Field(
        default=False,
        description="Set to true if user question requested unauthorized actions (e.g. approve payment, alter balances)",
    )


class InvestigationResponse(ProcureMindBaseSchema):
    """Authoritative API response returned to client."""

    transaction_id: uuid.UUID = Field(..., description="Canonical PostgreSQL transaction UUID")
    transaction_reference: str = Field(..., description="Human-readable transaction reference")
    discrepancy_id: uuid.UUID | None = Field(
        default=None, description="Focused discrepancy UUID if supplied and validated"
    )
    status: str = Field(
        ..., description="Resolution status: 'success', 'unavailable', or 'refusal'"
    )
    explanation: str = Field(
        ..., description="Grounded natural language narrative explaining the trade records"
    )
    authoritative_facts: AuthoritativeFinancialFacts = Field(
        ..., description="Authoritative calculations directly extracted from PostgreSQL"
    )
    cited_record_ids: list[uuid.UUID] = Field(
        default_factory=list,
        description="Validated record UUIDs confirmed to exist in the supplied context",
    )
    missing_information: list[str] = Field(
        default_factory=list,
        description="List of missing documents, evidence, or records needed for reconciliation",
    )
    suggested_next_action: str | None = Field(
        default=None,
        description="Recommended operational step for human auditor",
    )
    draft_clarification_message: str | None = Field(
        default=None,
        description="Drafted communication message for counterparty",
    )
    requires_human_review: bool = Field(
        default=True,
        description="Human auditor oversight required flag",
    )
    provider: str = Field(..., description="Provider identity (e.g. gemini, mock, unavailable)")
    warnings: list[str] = Field(
        default_factory=list,
        description="System warnings (e.g. citation hallucination warnings, currency mismatches)",
    )
